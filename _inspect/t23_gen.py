for d, x, tex, is_box in rows:
    if is_box:
        print(f"    \\wcbx{{{x:.2f}}}{{{d:.2f}}}")
    else:
        print(f"    \\wtx{{{x:.2f}}}{{{d:.2f}}}{{{tex}}}")
    prev_depth = d
