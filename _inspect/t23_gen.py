tahb = TTFont('/home/cloude/from-word-to-latex/latex/fonts/Tahoma-Bold.ttf')
upm = tah['head'].unitsPerEm
cmap = tah.getBestCmap()
cmapb = tahb.getBestCmap()
LSB_BOX = 1.328

def lsb(font, cm, ch):
    return font['hmtx'][cm[ord(ch)]][1] / upm * 10

